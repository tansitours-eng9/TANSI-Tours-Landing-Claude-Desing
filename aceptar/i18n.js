window.TANSI_getLang = function () {
  const params = new URLSearchParams(window.location.search);
  const fromUrl = params.get('lang');
  if (fromUrl === 'en' || fromUrl === 'es') return fromUrl;
  const stored = localStorage.getItem('tansi-lang');
  if (stored === 'en' || stored === 'es') return stored;
  const browser = (navigator.language || '').toLowerCase();
  return browser.startsWith('es') ? 'es' : 'en';
};

window.TANSI_applyLang = function (lang) {
  const t = window.TANSI_I18N[lang];
  if (!t) return;
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
    const key = el.getAttribute('data-i18n-html');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) el.placeholder = t[key];
  });

  if (document.title !== undefined && t.pageTitle) document.title = t.pageTitle;

  var clausesEl = document.getElementById('clausulas');
  if (clausesEl && t.clauses) {
    clausesEl.innerHTML = t.clauses.map(function (c, i) {
      var border = c.warn ? 'border-orange-200 bg-orange-50/30' : (c.legal ? 'border-green-200 bg-green-50/30' : 'border-gray-100');
      var summaryBg = c.warn ? 'hover:bg-orange-50' : (c.legal ? 'hover:bg-green-50' : 'bg-softOffWhite hover:bg-gray-50');
      var numBg = c.warn ? 'bg-orange-500' : (c.legal ? 'bg-green-600' : 'bg-primary');
      var bodyBorder = c.warn ? 'border-orange-100' : (c.legal ? 'border-green-100' : 'border-gray-100');
      return '<details class="clausula group border ' + border + ' rounded-xl overflow-hidden">' +
        '<summary class="flex items-center justify-between gap-3 p-4 ' + summaryBg + ' transition-colors">' +
        '<span class="flex items-center gap-3 text-sm font-semibold text-primary">' +
        '<span class="w-7 h-7 rounded-lg ' + numBg + ' text-white text-xs font-bold flex items-center justify-center shrink-0">' + (i + 1) + '</span>' +
        c.title + '</span>' +
        '<i data-lucide="chevron-down" class="chevron w-5 h-5 text-lightText transition-transform shrink-0"></i></summary>' +
        '<div class="p-4 text-sm text-darkText leading-relaxed border-t ' + bodyBorder + '">' + c.body + '</div></details>';
    }).join('');
    if (window.lucide) lucide.createIcons();
  }

  document.querySelectorAll('input[type=checkbox][name^="acepta_"]').forEach(function (cb) {
    cb.value = t.checkboxValue;
  });

  var subject = document.querySelector('[name="_subject"]');
  if (subject) subject.value = t.formSubject;
  var langField = document.getElementById('field-idioma');
  if (langField) langField.value = lang;

  document.getElementById('btn-lang-en').classList.toggle('bg-primary', lang === 'en');
  document.getElementById('btn-lang-en').classList.toggle('text-white', lang === 'en');
  document.getElementById('btn-lang-en').classList.toggle('text-lightText', lang !== 'en');
  document.getElementById('btn-lang-es').classList.toggle('bg-primary', lang === 'es');
  document.getElementById('btn-lang-es').classList.toggle('text-white', lang === 'es');
  document.getElementById('btn-lang-es').classList.toggle('text-lightText', lang !== 'es');

  localStorage.setItem('tansi-lang', lang);
  window.TANSI_currentLang = lang;
};

window.TANSI_setLang = function (lang) {
  window.TANSI_applyLang(lang);
  var params = new URLSearchParams(window.location.search);
  params.set('lang', lang);
  history.replaceState(null, '', window.location.pathname + '?' + params.toString());
};
